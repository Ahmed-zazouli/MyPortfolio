document.addEventListener('DOMContentLoaded', () => {
    // Initialize AOS Animations
    AOS.init({
        once: false, // animate every time the user scrolls
        offset: 50, // offset (in px) from the original trigger point
    });

    // Set current year in footer
    const yearSpan = document.getElementById('current-year');
    if (yearSpan) {
        yearSpan.textContent = new Date().getFullYear();
    }

    // --- DARK MODE LOGIC ---
    const darkModeToggle = document.getElementById('darkModeToggle');
    const htmlElement = document.documentElement;
    const bodyElement = document.body;

    // Check local storage for preference
    const currentTheme = localStorage.getItem('theme') || 'light';
    if (currentTheme === 'dark') {
        htmlElement.setAttribute('data-theme', 'dark');
        darkModeToggle.innerHTML = '<i class="fas fa-sun text-warning"></i>';

        // Ensure nav stays dark in dark mode
        const navbar = document.querySelector('.navbar');
        navbar.classList.remove('bg-dark');
        navbar.classList.add('bg-black');
    }

    darkModeToggle.addEventListener('click', () => {
        const isDark = htmlElement.getAttribute('data-theme') === 'dark';
        const navbar = document.querySelector('.navbar');

        if (isDark) {
            htmlElement.removeAttribute('data-theme');
            localStorage.setItem('theme', 'light');
            darkModeToggle.innerHTML = '<i class="fas fa-moon"></i>';
            navbar.classList.remove('bg-black');
            navbar.classList.add('bg-dark');
        } else {
            htmlElement.setAttribute('data-theme', 'dark');
            localStorage.setItem('theme', 'dark');
            darkModeToggle.innerHTML = '<i class="fas fa-sun text-warning"></i>';
            navbar.classList.remove('bg-dark');
            navbar.classList.add('bg-black');
        }
    });

    // --- LANGUAGE LOGIC ---
    const langSwitches = document.querySelectorAll('.lang-switch');
    const currentLangDisplay = document.getElementById('currentLang');

    // Check local storage for language
    let currentLang = localStorage.getItem('lang') || 'en';
    setLanguage(currentLang);

    langSwitches.forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            const selectedLang = e.target.getAttribute('data-lang');
            setLanguage(selectedLang);
        });
    });

    function setLanguage(lang) {
        localStorage.setItem('lang', lang);

        // Update display text in navbar
        currentLangDisplay.textContent = lang.toUpperCase();

        // RTL Support for Arabic
        if (lang === 'ar') {
            document.documentElement.setAttribute('dir', 'rtl');
            document.documentElement.setAttribute('lang', 'ar');
        } else {
            document.documentElement.removeAttribute('dir');
            document.documentElement.setAttribute('lang', lang);
        }

        // Translate elements
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                element.textContent = translations[lang][key];
            }
        });

        // Refresh AOS to recalculate positions after layout changes (RTL)
        setTimeout(() => {
            AOS.refresh();
        }, 300);
    }

    // --- SMOOTH SCROLLING ---
    const navLinks = document.querySelectorAll('.navbar-nav .nav-link');
    const navbarToggler = document.querySelector('.navbar-toggler');
    const navbarCollapse = document.querySelector('.navbar-collapse');

    navLinks.forEach(link => {
        link.addEventListener('click', function(e) {
            // Check if it's an internal link
            if (this.hash !== "") {
                const targetId = this.hash;
                const targetElement = document.querySelector(targetId);

                if (targetElement) {
                    e.preventDefault();

                    // Close the mobile navbar if it's open
                    if (navbarCollapse.classList.contains('show')) {
                        navbarToggler.click();
                    }

                    // Calculate position considering the fixed navbar
                    const headerOffset = 70;
                    const elementPosition = targetElement.getBoundingClientRect().top;
                    const offsetPosition = elementPosition + window.pageYOffset - headerOffset;

                    window.scrollTo({
                        top: offsetPosition,
                        behavior: "smooth"
                    });
                }
            }
        });
    });

    // Add active class to nav links on scroll (ScrollSpy fallback)
    const sections = document.querySelectorAll("section");

    window.addEventListener("scroll", () => {
        let current = "";

        sections.forEach((section) => {
            const sectionTop = section.offsetTop;
            const sectionHeight = section.clientHeight;
            // Add a small offset (80px) to trigger activation slightly before top
            if (pageYOffset >= sectionTop - 80) {
                current = section.getAttribute("id");
            }
        });

        navLinks.forEach((link) => {
            link.classList.remove("active");
            if (link.getAttribute("href") === `#${current}`) {
                link.classList.add("active");
            }
        });
    });
});